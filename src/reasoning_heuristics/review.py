"""Build every Stage 1 item set, then write human review packets and the summary.

    python -m reasoning_heuristics.review                 # smoke + dev (seed 1), test batch for leakage
    python -m reasoning_heuristics.review --only C:E1     # one eval
    python -m reasoning_heuristics.review --reuse         # rewrite the markdown from existing files

Outputs:
- data/items/{smoke,dev}/<V>_<E>_<tier>_s<seed>.jsonl, a deterministic .jsonl.gz copy (the
  committed form) and .report.json; test batches go to the gitignored data/items/test/ and
  are used only for the dev-vs-test leakage check;
- review/<V>_<E>.md: ~5 representative dev items (prompt, truth, member predictions, hypotheses);
- review/summary.md: items per eval and tier, cell coverage, validator pass rates, failures, leakage.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any

from reasoning_heuristics import tokens
from reasoning_heuristics.generate import ROOT, generate_and_validate, output_path
from reasoning_heuristics.generators import REGISTRY, load
from reasoning_heuristics.schema.item import Item, compress, read_jsonl
from reasoning_heuristics.validate.checks import check_leakage

ITEMS = ROOT / "data" / "items"
REVIEW = ROOT / "review"


def slug(vertical: str, eval_id: str) -> str:
    return f"{vertical.replace('/', '')}_{eval_id}"


def _short(value: Any, limit: int = 160) -> str:
    text = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _answer_text(rec: dict[str, Any]) -> str:
    if rec["answer"] is not None:
        a = rec["answer"]
        if isinstance(a, dict):
            return _short(" ".join(f"{k}={'T' if v is True else 'F' if v is False else v}" for k, v in a.items()), 120)
        return _short(a, 120)
    dist = rec.get("distribution") or {}
    top = sorted(dist.items(), key=lambda kv: -kv[1])[:2]
    return "; ".join(f"P({_short(k, 30)})={v:.2f}" for k, v in top) or "—"


def pick_representative(items: list[Item], k: int = 5) -> list[Item]:
    """One item from each of k different cells, spread over different sets where possible."""
    chosen, seen_cells, seen_sets = [], set(), Counter()
    for it in sorted(items, key=lambda x: (x.set_id, x.cell)):
        if it.cell in seen_cells:
            continue
        if seen_sets[it.set_id] >= 2:
            continue
        chosen.append(it)
        seen_cells.add(it.cell)
        seen_sets[it.set_id] += 1
        if len(chosen) == k:
            break
    return chosen


def render_item(it: Item) -> str:
    lines = [
        f"### {it.cell} — set `{it.set_id}`",
        "",
        f"- **Domain / framing:** {it.domain} / {it.framing}",
        f"- **Ground truth:** `{_short(it.ground_truth, 300)}`",
        f"- **Hashes:** content `{it.content_hash}`, base `{it.base_hash}`, source `{it.source_hash}`; seed {it.seed} ({it.split})",
        f"- **Params:** `{_short({k: v for k, v in it.params.items() if k not in ('frame',)}, 300)}`",
        f"- **Prompt tokens ({tokens.PROXY_NAME}):** {tokens.count(it.prompt)}",
        "",
        "<details><summary>Prompt</summary>",
        "",
        "```text",
        it.prompt,
        "```",
        "",
        "</details>",
        "",
        "| Member | Family | Prediction | Eval prediction | Trace signature |",
        "|---|---|---|---|---|",
    ]
    for label, rec in it.predictions.items():
        hyp = it.hypotheses.get(label, {})
        lines.append(f"| {label} | {rec['family']} | {_answer_text(rec)} | {_short(hyp.get('eval_prediction', ''), 140)} "
                     f"| {_short(hyp.get('cot_prediction', ''), 110)} |".replace("\n", " "))
    lines += ["", "Log10 LR against each theory, by observed outcome (positive = evidence against; top 4 rows):", ""]
    for outcome, row in list(it.disconfirms.items())[:4]:
        worst = sorted(row.items(), key=lambda kv: -kv[1])[:6]
        lines.append(f"- *{_short(outcome, 90)}*: " + ", ".join(f"{h} {v:+.2f}" for h, v in worst))
    if it.notes:
        lines += ["", f"Notes: {it.notes}"]
    return "\n".join(lines) + "\n"


def write_packet(mod: Any, dev_items: list[Item], report: dict[str, Any]) -> Path:
    doc = (mod.__doc__ or "").strip()
    v = report.get("validation", {})
    lines = [
        f"# Review packet: {mod.VERTICAL} {mod.EVAL_ID}",
        "",
        f"Generated by `python -m reasoning_heuristics.review` from the dev batch "
        f"(`{report['path']}`, {len(dev_items)} items, {v.get('items_passed', '?')} pass the validators).",
        "Five representative items follow, each from a different design cell. Every prediction below was computed",
        "by the reference implementation named in the predictions record and recomputed by the validators.",
        "",
        "## Generator design (module docstring)",
        "",
        "```text",
        doc,
        "```",
        "",
        "## Items",
        "",
    ]
    for it in pick_representative(dev_items):
        lines.append(render_item(it))
    path = REVIEW / f"{slug(mod.VERTICAL, mod.EVAL_ID)}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    return path


def coverage(items: list[Item], designed: list[str]) -> dict[str, Any]:
    counts = Counter(it.cell for it in items)
    missing = [c for c in designed if counts[c] == 0]
    extra = sorted(set(counts) - set(designed))
    per = [counts[c] for c in designed]
    return {"designed_cells": len(designed), "covered": len(designed) - len(missing), "missing": missing,
            "undesigned_cells": extra, "min_per_cell": min(per) if per else 0, "max_per_cell": max(per) if per else 0}


def build(only: list[tuple[str, str]] | None, seed: int, reuse: bool, dev_per_cell: int | None) -> list[dict[str, Any]]:
    rows = []
    for (vertical, eval_id) in REGISTRY:
        if only and (vertical, eval_id) not in only:
            continue
        mod = load(vertical, eval_id)
        reports = {}
        for tier, per in (("smoke", None), ("dev", dev_per_cell), ("test", 1)):
            path = output_path(ITEMS, mod.VERTICAL, mod.EVAL_ID, tier, seed)
            rpath = path.with_suffix(".report.json")
            if reuse and rpath.exists():
                reports[tier] = json.loads(rpath.read_text())
            else:
                print(f"generating {vertical} {eval_id} {tier} ...", flush=True)
                reports[tier] = generate_and_validate(mod.VERTICAL, mod.EVAL_ID, tier, seed, per, {}, ITEMS,
                                                      validate=(tier != "test"))
            reports[tier]["items_list"] = read_jsonl(path)
            if tier != "test":
                compress(path)
        smoke, dev, test = (reports[t]["items_list"] for t in ("smoke", "dev", "test"))
        leak = check_leakage(dev + smoke + test, lexicon_partitioned=mod.LEXICON_PARTITIONED)
        overlap = {it.base_hash for it in smoke} & {it.base_hash for it in dev}
        write_packet(mod, dev, reports["dev"])
        designed = mod.cells({})
        rows.append({
            "vertical": mod.VERTICAL, "eval_id": mod.EVAL_ID,
            "tiers": {t: {"items": len(reports[t]["items_list"]),
                          "bases": reports[t]["generation"]["accepted"],
                          "attempts": reports[t]["generation"]["attempts"],
                          "seconds": reports[t].get("generation_seconds"),
                          "coverage": coverage(reports[t]["items_list"], designed),
                          "validation": {k: v for k, v in reports[t].get("validation", {}).items()}}
                      for t in ("smoke", "dev")},
            "leakage_failures": [f.to_json() for f in leak],
            "smoke_dev_shared_bases": len(overlap),
            "test_items_checked": len(test),
        })
    return rows


def write_summary(rows: list[dict[str, Any]], seed: int) -> Path:
    lines = [
        "# Stage 1 item sets: summary",
        "",
        f"Built by `python -m reasoning_heuristics.review` (user seed {seed}). Smoke = 1 item per design cell;",
        "dev = 5 per cell unless stated. Smoke, dev and test bases come from disjoint seed ranges",
        "(smoke [0, 1e5), dev [1e5, 1e6), test [1e6, 2e6)). A one-item-per-cell test batch is generated",
        "only to check dev-vs-test leakage; it is not committed.",
        "",
        "| Eval | Smoke items | Dev items | Dev bases (attempts) | Cells covered (dev) | Items per cell (dev) | Smoke pass | Dev pass | Leakage | Dev gen. time |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    failures = []
    for r in rows:
        s, d = r["tiers"]["smoke"], r["tiers"]["dev"]
        cov = d["coverage"]
        leak = "none" if not r["leakage_failures"] and not r["smoke_dev_shared_bases"] else f"{len(r['leakage_failures'])} + {r['smoke_dev_shared_bases']} shared"
        lines.append(
            f"| {r['vertical']} {r['eval_id']} | {s['items']} | {d['items']} | {d['bases']} ({d['attempts']}) | "
            f"{cov['covered']}/{cov['designed_cells']} | {cov['min_per_cell']}–{cov['max_per_cell']} | "
            f"{s['validation'].get('pass_rate', 0):.0%} | {d['validation'].get('pass_rate', 0):.0%} | {leak} | {d['seconds']} s |")
        for t in ("smoke", "dev"):
            for f in r["tiers"][t]["validation"].get("failures", []):
                failures.append(f"| {r['vertical']} {r['eval_id']} | {t} | `{f['item_id']}` | {f['check']} | {_short(f['message'], 120)} |")
        for f in r["leakage_failures"]:
            failures.append(f"| {r['vertical']} {r['eval_id']} | leakage | `{f['item_id']}` | {f['check']} | {_short(f['message'], 120)} |")
    total_smoke = sum(r["tiers"]["smoke"]["items"] for r in rows)
    total_dev = sum(r["tiers"]["dev"]["items"] for r in rows)
    lines += ["", f"**Totals:** {total_smoke} smoke items and {total_dev} dev items across {len(rows)} evals.", ""]
    missing = [(r, r["tiers"]["dev"]["coverage"]["missing"]) for r in rows if r["tiers"]["dev"]["coverage"]["missing"]]
    if missing:
        lines += ["## Cells with no dev items", ""]
        for r, cells in missing:
            lines.append(f"- {r['vertical']} {r['eval_id']}: {', '.join(cells)}")
        lines.append("")
    lines += ["## Items that failed validation", ""]
    if failures:
        lines += ["| Eval | Tier | Item | Check | Message |", "|---|---|---|---|---|"] + failures
    else:
        lines.append("None. Every smoke and dev item passed every validator, and no dev base leaks into the test batch.")
    lines += ["", "## Validators", "",
              "Item checks: schema, hashes, seed range, ground truth recomputed by an independent solver, every",
              "prediction recomputed from (instance, member, params), and discrimination (two or more members",
              "disagree). Set checks: each generator's designed invariants (see the review packets). Leakage:",
              "dev vs test bases by hash and by isomorphism (graphs, CNF, premise structure), or by lexicon",
              "partition for B4/C4.", ""]
    path = REVIEW / "summary.md"
    path.write_text("\n".join(lines))
    (REVIEW / "summary.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False, default=str))
    return path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", action="append", default=[], help="VERTICAL:EVAL, e.g. C:E1 or B4/C4:E2")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--reuse", action="store_true", help="reuse existing item files and reports")
    ap.add_argument("--dev-per-cell", type=int, default=None)
    args = ap.parse_args(argv)
    from reasoning_heuristics.generators import canonical_vertical

    only = [(canonical_vertical(o.split(":")[0]), o.split(":")[1].upper()) for o in args.only] or None
    rows = build(only, args.seed, args.reuse, args.dev_per_cell)
    if only:
        # Merge with existing rows for other evals so the summary stays complete.
        old = REVIEW / "summary.json"
        if old.exists():
            keep = [r for r in json.loads(old.read_text()) if (r["vertical"], r["eval_id"]) not in set(only)]
            rows = sorted(keep + rows, key=lambda r: list(REGISTRY).index((r["vertical"], r["eval_id"])))
    print(write_summary(rows, args.seed))
    bad = sum(len(r["tiers"][t]["validation"].get("failures", [])) for r in rows for t in ("smoke", "dev"))
    bad += sum(len(r["leakage_failures"]) + r["smoke_dev_shared_bases"] for r in rows)
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
